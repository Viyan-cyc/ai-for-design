import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
const here=path.dirname(fileURLToPath(import.meta.url));
const scripts=path.resolve(here,'../../skills/gts-charts-coder/scripts');
const work=fs.mkdtempSync(path.join(os.tmpdir(),'ep-charts-check-'));
const project=path.join(work,'charts-check');
function run(name,args){const p=spawnSync(process.execPath,[path.join(name.startsWith('check-')?path.resolve(here,'../../tools/gts-charts-coder'):scripts,name),...args],{encoding:'utf8',timeout:30000});return {code:p.status,text:p.stdout+p.stderr};}
assert.equal(run('init.mjs',[work,'charts-check']).code,0);
const initialPage=fs.readFileSync(path.join(project,'src/pages/ChartsCheck/index.vue'),'utf8');
assert.match(initialPage,/echarts\.init/);
assert(!/ElTable|ElPagination|getDeviceList/.test(initialPage));
assert.equal(run('build.mjs',['--dir',project]).code,0);
fs.cpSync(path.join(here,'fixture/src'),path.join(project,'src'),{recursive:true});
const page=path.join(project,'src/pages/ChartsCheck/index.vue');
const original=fs.readFileSync(page,'utf8');
function build(ok,match){const r=run('build.mjs',['--dir',project]);assert.equal(r.code,ok?0:1,r.text);if(match)assert.match(r.text,match);}
build(true);
const css=path.join(project,'src/assets/charts/test.css');
const valid=fs.readFileSync(css,'utf8');
fs.writeFileSync(css,'html { --page-chart-series: #2070F3; }');build(false,/container class/);
fs.writeFileSync(css,'.chart-test { --el-color-primary: #2070F3; }');build(false,/chart token requires/);
fs.writeFileSync(css,'--page-chart-series: #2070F3;');build(false,/inside a container class/);
fs.writeFileSync(css,valid);
fs.writeFileSync(page,original.replace("import * as echarts from 'echarts'","import * as echarts from 'echarts/core'"));build(false,/unmapped module/);
fs.writeFileSync(page,original.replace('width:100%','color:var(--missing-chart-token);width:100%'));build(false,/unknown token/);
fs.writeFileSync(page,original.replace("import '../../assets/charts/test.css'","import '../../assets/charts/missing.css'"));build(false,/missing\/outside import/);
fs.writeFileSync(page,original.replace("series:[{type:'bar',data:data.values,itemStyle:{color:getComputedStyle(host.value).getPropertyValue('--page-chart-series').trim()}}]","parallelAxis:[{dim:0,name:'A'},{dim:1,name:'B'},{dim:2,name:'C'}],series:[{type:'parallel',data:[[1,2,3],[3,2,1]]}]"));build(true);
assert.equal(run('check-upstream.mjs',[]).code,0);
assert.equal(run('check-upstream.mjs',['--source']).code,2);
assert.equal(run('check-upstream.mjs',['--kind','engineering']).code,0);
assert.equal(run('check-package.mjs',[]).code,0);
const changedSource=path.join(work,'changed-design');fs.mkdirSync(changedSource);fs.writeFileSync(path.join(changedSource,'new.md'),'new source');
const changed=run('check-upstream.mjs',['--source',changedSource]);assert.equal(changed.code,1);assert.match(changed.text,/ADDED: new.md/);assert.match(changed.text,/REMOVED:/);
assert.equal(run('check-upstream.mjs',['--kind','engineering','--source',changedSource]).code,1);
console.log('RESULT: OK\nCHECKS: 15\nRUNTIME: not-run\nFIXTURE_DIR: '+project);
