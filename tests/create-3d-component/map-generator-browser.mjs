import {chromium} from '../../tools/3d-component-studio/node_modules/playwright/index.mjs';
import {readFile,writeFile} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import assert from 'node:assert/strict';
const evidence=resolve(process.argv[2]),server=JSON.parse(await readFile(join(evidence,'server.json'),'utf8'));
const browser=await chromium.launch({channel:'msedge',headless:true,args:['--ignore-certificate-errors']});
const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[],checks=[];
page.on('pageerror',e=>errors.push(String(e)));
try{
 await page.goto(server.url+'/r8-test.html',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>window.r8,null,{timeout:90000});
 const snapshot=()=>page.evaluate(()=>window.r8.handle.serialize().map);
 assert.equal((await snapshot()).runtime,'experience');
 assert.equal(await page.locator('[aria-label="地图组件参数"]').count(),1);
 assert.equal(await page.locator('[aria-label="逻辑散点（非地理图层）"] canvas').count(),1);
 checks.push('actual generated scene and editor panel loaded');
 await page.getByRole('checkbox',{name:'显示栅格',exact:true}).uncheck();
 assert.equal((await snapshot()).heat.gridVisible,false);assert.equal((await snapshot()).heat.tint.enabled,true);
 assert.equal(await page.evaluate(()=>window.r8.save.dirty.value),true);
 await page.evaluate(()=>window.r8.bridge.undo());assert.equal((await snapshot()).heat.gridVisible,true);
 await page.evaluate(()=>window.r8.bridge.redo());assert.equal((await snapshot()).heat.gridVisible,false);
 checks.push('public UI grid toggle independent of tint, dirty, undo and redo');
 await page.getByRole('slider',{name:'建筑明度',exact:true}).fill('1.2');
 await page.getByRole('slider',{name:'建筑明度',exact:true}).dispatchEvent('change');
 assert.equal((await snapshot()).heat.tint.brightness,1.2);
 await page.getByRole('slider',{name:'散点半径',exact:true}).fill('5.2');
 await page.getByRole('slider',{name:'散点半径',exact:true}).dispatchEvent('change');
 assert.equal((await snapshot()).logicalScatter.options.pointRadius,5.2);
 await page.getByLabel('地图水域颜色',{exact:true}).fill('#123456');
 await page.getByLabel('地图水域颜色',{exact:true}).dispatchEvent('change');
 assert.equal((await snapshot()).experience.parameters.water,'#123456');
 checks.push('map, tint and scatter controls update serialized public state');
 const invalid=await page.evaluate(()=>{const {handle,bridge,save}=window.r8;const before=JSON.stringify(handle.serialize()),depth=bridge.getState().undoDepth;const bad=handle.serialize();bad.map.heat.data=[{lng:0,lat:0,value:999}];let rejected=false;try{save.importText(JSON.stringify(bad));}catch{rejected=true;}return{rejected,same:before===JSON.stringify(handle.serialize()),depth:depth===bridge.getState().undoDepth};});
 assert.deepEqual(invalid,{rejected:true,same:true,depth:true});checks.push('invalid import rejected before mutation and history');
 await page.getByRole('button',{name:'清空热力数据',exact:true}).click();assert.deepEqual((await snapshot()).heat.data,[]);
 await page.evaluate(()=>window.r8.bridge.undo());assert.ok((await snapshot()).heat.data.length>0);
 checks.push('empty data and undo restore');
 await page.evaluate(async()=>{await window.r8.save.save();});
 assert.equal(await page.evaluate(()=>window.r8.save.status.value),'已保存到源码');
 assert.equal(await page.evaluate(()=>window.r8.save.dirty.value),false);
 const disk=JSON.parse(await readFile(join(server.source,'public/scene3d/scene-data.json'),'utf8'));
 assert.equal(disk.map.heat.tint.brightness,1.2);assert.equal(disk.map.logicalScatter.options.pointRadius,5.2);assert.equal(disk.map.experience.parameters.water,'#123456');
 checks.push('real SaveService POST writes current generated source');
 await page.reload({waitUntil:'domcontentloaded'});await page.waitForFunction(()=>window.r8,null,{timeout:90000});
 assert.equal((await snapshot()).heat.tint.brightness,1.2);assert.equal((await snapshot()).logicalScatter.options.pointRadius,5.2);assert.equal((await snapshot()).experience.parameters.water,'#123456');
 checks.push('close/reload reads saved scene');
 await page.evaluate(()=>window.r8.dispose());assert.equal(await page.locator('.maplibregl-canvas').count(),0);assert.equal(await page.locator('[aria-label="逻辑散点（非地理图层）"]').count(),0);
 checks.push('dispose removes both map and logical canvas');
 assert.deepEqual(errors,[]);
 await writeFile(join(evidence,'browser.json'),JSON.stringify({status:'passed',checks,errors,screenshots:false,visual:'not-evaluated'},null,2));
 console.log(JSON.stringify({checks,errors},null,2));
}catch(e){await writeFile(join(evidence,'browser-failure.json'),JSON.stringify({error:String(e),checks,errors},null,2));throw e;}finally{await browser.close();}
