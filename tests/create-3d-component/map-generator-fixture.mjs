import {readFile,writeFile} from 'node:fs/promises';
import {join,resolve} from 'node:path';
const root=resolve(process.argv[2]);
const file=join(root,'public/data/scene.json');
const data=JSON.parse(await readFile(file,'utf8'));
const origin=[121.49517,31.24194], records=[];
for(let x=-12;x<13;x++)for(let y=-12;y<13;y++)records.push({lng:origin[0]+(x+.5)*14/(111320*Math.cos(origin[1]*Math.PI/180)),lat:origin[1]+(y+.5)*14/111320,value:Math.round(80+175*Math.max(0,1-Math.hypot(x,y)/18))});
data.map={runtime:'experience',styleUrl:'https://tiles.openfreemap.org/styles/liberty',origin,center:origin,zoom:16.5,pitch:45,view:'3d',theme:'light',experience:{parameters:{}},heat:{data:records,options:{origin,colorBlur:0},gridVisible:true,tint:{enabled:true,brightness:1.5}},logicalScatter:{data:Array.from({length:40},(_,i)=>({id:'p'+i,x:.2+(i%8)*.07,y:.25+Math.floor(i/8)*.08})),options:{},zoom:.12,visible:true}};
data.r8models=[{id:'r8-pbr',position:[0,45,0]}];
await writeFile(file,JSON.stringify(data,null,2)+'\n');
const profile=join(root,'src/3d/scene-profile.ts');
let code=await readFile(profile,'utf8');
if(!code.includes('r8models:'))code="import * as THREE from 'three';\n"+code.replace('= {};',"= {r8models:({sceneEngine})=>sceneEngine.registerFactory('r8models',()=>new THREE.Mesh(new THREE.BoxGeometry(42,90,42),new THREE.MeshStandardMaterial({color:0xeeeeee})))};");
await writeFile(profile,code);
await writeFile(join(root,'r8-test.html'),'<!doctype html><html><body style="margin:0"><div id="map" style="position:relative;width:100vw;height:100vh"></div><div id="panel" style="position:fixed;right:0;top:0;background:white;width:300px;max-height:100vh;overflow:auto;z-index:9"></div><script type="module" src="/src/r8-test.ts"></script></body></html>');
await writeFile(join(root,'src/r8-test.ts'),`import {createScene3D} from './scene';
import {Bridge} from './edit/Bridge';
import {SaveService} from './edit/SaveService';
import Panel from './edit/MapComponentsPanel.vue';
import {createApp} from 'vue';
const handle=await createScene3D(document.querySelector('#map')!);
const bridge=new Bridge(handle),save=new SaveService(handle,bridge);
const app=createApp(Panel,{bridge});app.mount('#panel');
const model=handle.internals.sceneEngine.getObject('r8-pbr');
(window as any).r8={handle,bridge,save,model,dispose(){app.unmount();save.dispose();handle.dispose();}};
`);
console.log(root);
