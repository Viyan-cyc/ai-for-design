import assert from 'node:assert/strict';
import {mkdtemp,readFile,writeFile,cp,mkdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {exportSuite,unpackSuite} from '../../tools/3d-component-studio/intake/map-suite.mjs';
import {readZip,writeZip} from '../../tools/3d-component-studio/native-template/example/zip.mjs';
const source=resolve(process.argv[2]),work=await mkdtemp(join(tmpdir(),'map-suite-contract-'));
const candidate=join(work,'candidate');await cp(source,candidate,{recursive:true});
const zip=join(work,'valid.zip');await exportSuite(candidate,zip);const good=join(work,'unpacked');await unpackSuite(zip,good);
await assert.rejects(()=>unpackSuite(zip,good),/exist/);
await assert.rejects(()=>exportSuite(candidate,zip),/exist/);
const files=readZip(new Uint8Array(await readFile(zip)));
files['src/heat-field/field.ts']=new TextEncoder().encode('export const corrupt=true');
await writeFile(join(work,'tampered.zip'),writeZip(files));
await assert.rejects(()=>unpackSuite(join(work,'tampered.zip'),join(work,'bad')),/清单/);
delete files['suite-manifest.json'];await writeFile(join(work,'missing.zip'),writeZip(files));
await assert.rejects(()=>unpackSuite(join(work,'missing.zip'),join(work,'missing')),/清单/);
await writeFile(join(candidate,'src','index.ts'),'broken');
// An exported candidate cannot silently be resealed after source changes.
await writeFile(join(good,'src','index.ts'),'broken');
await assert.rejects(()=>exportSuite(good,join(work,'reseal.zip')),/清单/);
const extra=join(candidate,'example');await mkdir(extra);await writeFile(join(extra,'demo.js'),'');
await assert.rejects(()=>exportSuite(candidate,join(work,'extra.zip')),/非法套件文件/);
assert.throws(()=>writeZip({'../escape.ts':new Uint8Array()}),/路径/);
const badPlan=join(work,'bad-plan.json');await writeFile(badPlan,JSON.stringify({format:'map-suite-plan',version:1,destination:'../../escape'}));
const refused=spawnSync(process.execPath,[fileURLToPath(new URL('../../tools/3d-component-studio/intake/map-suite.mjs',import.meta.url)),'verify',badPlan,join(work,'no-write')],{encoding:'utf8'});
assert.equal(refused.status,1);assert.match(refused.stderr,/非法计划目标/);
console.log(JSON.stringify({passed:9,work,checks:['roundtrip','no-unpack-overwrite','no-export-overwrite','tamper','missing-manifest','no-silent-reseal','no-demo','no-path-traversal','no-plan-path-traversal']}));
