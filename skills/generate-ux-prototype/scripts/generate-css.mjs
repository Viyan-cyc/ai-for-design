// 不再产出（旧集退役项，第 10 步删除）：
//   semantic-dark.css  旧深色语义映射是工程自造值，GTS 2.2 深色 UI 未定义；data-theme="dark"
//                      协议位保留，code/frost/border-width 有真源深色值照发
//   glass.css          旧 aurora-glass 遗留，新包 frost 体系统一
//   component.css + components/*.css   g-* 兼容层：patterns 迁移（第 5 步）换新名后退役
//   frost-decoration.css               并入 frost.css（装饰参数进种子）
//
// Usage:
//   node generate-css.mjs --tokens <tokens.json> --out <tokens-dir> [--check-only]

