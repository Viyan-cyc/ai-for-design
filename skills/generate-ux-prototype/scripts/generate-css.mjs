function parseArgs(argv) {
  const args = {};
  for (let i = 2; i < argv.length; i++) {
    if (argv[i].startsWith('--')) args[argv[i].slice(2)] = argv[i + 1], i++;
  }
  return args;
}

const HEADER = (src) =>
  `/* GENERATED by scripts/generate-css.mjs from library/tokens.json (${src}). Do not edit — re-run the pipeline. */\n`;

// ---------- helpers ----------
const v = (t) => t.$value;
const cssRef = (name) => `var(--${name})`;

function shadowCss(sh) {
  return `${sh.offsetX} ${sh.offsetY} ${sh.blur} ${sh.spread} ${sh.color}`;
}

function fontFamilyCss(stack) {
  return stack.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(', ');
}

// DTCG {alias} → var(--alias)
function resolveCss(value, tokens) {
  if (typeof value === 'string') {
    const m = value.match(/^\{(.+)\}$/);
    return m ? cssRef(m[1]) : value;
  }
  if (Array.isArray(value)) return fontFamilyCss(value);
  if (typeof value === 'object' && value.offsetX) return shadowCss(value);
  return String(value);
}

// 语义色：纯色出 var() 链；透明叠加（gts.ref + $value 为 rgba 字面值）出 rgba(var(--ref) 字面) 不可能——
// CSS 无法对 var() 做 alpha 合成（color-mix 可但兼容面窄），与旧库一致：透明叠加直接落 rgba 字面值，
// gts.ref/alpha 只作审计。此决策与旧 semantic-light.css 行为一致。
function semanticLine(name, t) {
  const raw = typeof t.$value === 'string' && /^\{.+\}$/.test(t.$value)
    ? cssRef(t.$value.slice(1, -1))
    : t.$value;
  return `  --${name}: ${raw};`;
}

// ---------- primitive.css ----------
function genPrimitive(tokens, sourceVersion) {
  const L = [];
  const order = ['palette', 'dimension', 'shadow', 'fontFamily', 'fontWeight', 'strokeStyle'];
  const bucket = Object.fromEntries(order.map((k) => [k, []]));
  for (const [name, t] of Object.entries(tokens)) {
    if (t.$extensions?.gts?.source === 'backfill-g1.5.1') continue; // frost 种子走 frost.css
    if (t.$extensions?.gts?.hljs) continue;                          // code-* 走 code.css
    const type = t.$type === 'dimension' ? 'dimension'
      : t.$type === 'shadow' ? 'shadow'
      : t.$type === 'fontFamily' ? 'fontFamily'
      : t.$type === 'fontWeight' ? 'fontWeight'
      : t.$type === 'strokeStyle' ? 'strokeStyle'
      : t.$type === 'color' ? 'palette' : null;
    if (!type) continue;
    // 语义色属于 semantic.css（$extensions.gts.description 且名字以 color- 开头的纯语义层）
    if (type === 'palette' && name.startsWith('color-') && !name.startsWith('color-chart')) continue;
    if (type === 'palette' && name.startsWith('company-')) { bucket.palette.push([name, t]); continue; }
    bucket[type].push([name, t]);
  }

  L.push(HEADER(sourceVersion));
  L.push(`/* 基础层：字面值。来源=GTS 2.2 设计系统.md；语义层（semantic.css）以 var() 引用本层。 */`);
  L.push(`:root {`);
  for (const [name, t] of bucket.palette) L.push(`  --${name}: ${resolveCss(v(t), tokens)};`);
  for (const [name, t] of bucket.dimension) L.push(`  --${name}: ${resolveCss(v(t), tokens)};`);
  for (const [name, t] of bucket.fontFamily) L.push(`  --${name}: ${resolveCss(v(t), tokens)};`);
  for (const [name, t] of bucket.fontWeight) L.push(`  --${name}: ${resolveCss(v(t), tokens)};`);
  for (const [name, t] of bucket.strokeStyle) L.push(`  --${name}: ${resolveCss(v(t), tokens)};`);
  for (const [name, t] of bucket.shadow) L.push(`  --${name}: ${resolveCss(v(t), tokens)};`);
  L.push(`}`);

  // 真源深色差异（border-width-independent 等）
  const darkDim = Object.entries(tokens)
    .filter(([n, t]) => t.$extensions?.gts?.dark && t.$type === 'dimension');
  if (darkDim.length) {
    L.push(`[data-theme="dark"] {`);
    for (const [name, t] of darkDim) L.push(`  --${name}: ${t.$extensions.gts.dark};`);
    L.push(`}`);
  }
  return L.join('\n') + '\n';
}

// ---------- semantic.css ----------
// 语义分类按 extract 时的源顺序自然分组；这里按名前缀重排为语义可读顺序。
const SEMANTIC_ORDER = [
  'color-brand', 'color-text-', 'color-icon-', 'color-border', 'color-bg-',
  'color-hover', 'color-select', 'color-table-', 'color-fill',
  'color-error', 'color-alert', 'color-warning', 'color-success', 'color-info', 'color-none',
];

function semanticRank(name) {
  for (let i = 0; i < SEMANTIC_ORDER.length; i++) {
    if (name.startsWith(SEMANTIC_ORDER[i])) return i;
  }
  return 999;
}

function genSemantic(tokens, sourceVersion) {
  const semantic = Object.entries(tokens)
    .filter(([n, t]) =>
      n.startsWith('color-') && !n.startsWith('color-chart') &&
      !t.$extensions?.gts?.hljs && t.$type === 'color')
    .sort((a, b) => semanticRank(a[0]) - semanticRank(b[0]) || a[0].localeCompare(b[0]));

  const L = [];
  L.push(HEADER(sourceVersion));
  L.push(`/* 语义层：业务代码只引用本层（--color-*）。浅色为默认主题；
   [data-theme="dark"] 为工程回填（G 1.5.1 旧版值，设计师 2026-09-16 答复"用旧版值"），设计师正式修订后由 md 行取代。 */`);
  L.push(`:root,\n[data-theme="light"] {`);
  L.push(`  color-scheme: light;`);
  for (const [name, t] of semantic) L.push(semanticLine(name, t));
  L.push(`}`);

  // 深色覆盖：gts.dark = 设计真源（code-*）或工程回填（semantic-dark，darkSource 标注）
  const dark = semantic.filter(([, t]) => t.$extensions?.gts?.dark);
  if (dark.length) {
    L.push(`[data-theme="dark"] {`);
    L.push(`  color-scheme: dark;`);
    for (const [name, t] of dark) L.push(`  --${name}: ${darkCssValue(t)};`);
    L.push(`}`);
  }
  return L.join('\n') + '\n';
}

// 深色值出 CSS：别名 {x} → var(--x)；var(--x) 字面直接透传（回填种子原样）；rgba 字面直落
function darkCssValue(t) {
  const raw = t.$extensions.gts.dark;
  if (typeof raw !== 'string') return String(raw);
  const m = raw.match(/^\{(.+)\}$/);
  if (m) return cssRef(m[1]);
  return raw;
}

// ---------- charts.css ----------
// 源引用常量（GTS 2.2 图表节明文，非 token 表行）：尾部色 blue-70 + 延展三组合。
const CHART_TAIL = 'blue-70';
const CHART_EXTENSIONS = [
  ['extension-1', ['mint-50', 'indigo-40', 'cyan-50', 'purple-40']],
  ['extension-2', ['indigo-50', 'yellow-40', 'blue-50', 'green-40']],
  ['extension-3', ['purple-50', 'green-40', 'cyan-50', 'orange-40']],
];

function genCharts(tokens, sourceVersion) {
  const charts = [];
  for (let i = 1; i <= 6; i++) charts.push(tokens[`color-chart-${i}`]);
  const acc = charts.map((t) => t.$extensions.gts.accessible.slice(1, -1)); // {blue-60} → blue-60

  const L = [];
  L.push(HEADER(sourceVersion));
  L.push(`/* 图表配色：默认六色 + 无障碍组 + 延展组合。选组用 data-chart-palette；两组间不逐色拼接。 */`);
  L.push(`:root,\n[data-chart-palette="default"] {`);
  charts.forEach((t, i) => L.push(`  --color-chart-${i + 1}: ${cssRef(v(t).slice(1, -1))};`));
  L.push(`  --color-chart-tail: ${cssRef(CHART_TAIL)};`);
  acc.forEach((ref, i) => L.push(`  --color-chart-accessible-${i + 1}: ${cssRef(ref)};`));
  CHART_EXTENSIONS.forEach(([label, refs]) =>
    refs.forEach((ref, i) => L.push(`  --color-chart-extension-${label.slice(-1)}-${i + 1}: ${cssRef(ref)};`)));
  L.push(`}`);
  L.push(`[data-chart-palette="accessible"] {`);
  charts.forEach((t, i) => L.push(`  --color-chart-${i + 1}: ${cssRef(acc[i])};`));
  L.push(`}`);
  for (const [label, refs] of CHART_EXTENSIONS) {
    L.push(`[data-chart-palette="${label}"] {`);
    for (let i = 0; i < 6; i++) {
      L.push(`  --color-chart-${i + 1}: ${refs[i] ? cssRef(refs[i]) : 'initial'};`);
    }
    L.push(`}`);
  }
  return L.join('\n') + '\n';
}

// ---------- code.css ----------
function genCode(tokens, sourceVersion) {
  const code = Object.entries(tokens).filter(([n, t]) => !!t.$extensions?.gts?.hljs);
  const L = [];
  L.push(HEADER(sourceVersion));
  L.push(`/* 代码高亮（StarCode）：仅代码展示/编辑场景。浅色默认；深色为设计真源值。 */`);
  L.push(`:root,\n[data-theme="light"] {`);
  for (const [name, t] of code) L.push(`  --${name}: ${t.$value};`);
  L.push(`}`);
  L.push(`[data-theme="dark"] {`);
  for (const [name, t] of code) L.push(`  --${name}: ${t.$extensions.gts.dark};`);
  L.push(`}`);
  return L.join('\n') + '\n';
}

// ---------- frost.css ----------
// 种子 token 直出 + 规则层。规则层是调用约定的实现（data-material 等），
// 值全部 var() 引用 token；token 名与旧 frosted.css 兼容（--frost-blur-* 等），
// 设计师补齐正式表后 extract 解析同名 token 自动接管。
// 浅/深同名的扁平 token（alpha/surface/shadow/tint/backdrop/solid/border/neutral-rgb）：
// $value 为浅色（:root 默认主题），gts.dark 为深色（data-theme="dark" 覆盖）。
function genFrost(tokens, sourceVersion) {
  const frost = Object.entries(tokens).filter(([n, t]) => t.$extensions?.gts?.source === 'backfill-g1.5.1');
  const byGroup = (g) => frost.filter(([, t]) => t.$extensions.gts.group === g);

  const line = (name, t) => {
    const raw = t.$value;
    const out = typeof raw === 'string' && /^\{.+\}$/.test(raw) ? cssRef(raw.slice(1, -1)) : raw;
    return `  --${name}: ${out};`;
  };

  const L = [];
  L.push(HEADER(sourceVersion));
  L.push(`/* 毛玻璃（过渡基线）：数值为 G 1.5.1 已验证实现回填，待设计师复核（见 设计系统.md §7）。
   Token 层 :root 段由管线生成；规则层实现 §7.7 调用约定（data-material 协议）。 */`);

  // 全部种子（common + light + decoration）：:root 默认主题
  L.push(`:root {`);
  for (const [name, t] of frost) L.push(line(name, t));
  L.push(`}`);
  // 真源深色差异（gts.dark）→ data-theme="dark" 覆盖
  const darkPairs = frost.filter(([, t]) => t.$extensions?.gts?.dark);
  if (darkPairs.length) {
    L.push(`[data-theme="dark"] {`);
    for (const [name, t] of darkPairs) L.push(`  --${name}: ${t.$extensions.gts.dark};`);
    L.push(`}`);
  }

  // 规则层：值全部引用 token，与旧 frosted.css/frost-decoration.css 行为一致（g-glass-* 遗留选择器已移除）
  L.push(`/* ---- 规则层：§7.7 调用约定实现 ---- */`);
  L.push(FROST_RULES);
  return L.join('\n') + '\n';
}

