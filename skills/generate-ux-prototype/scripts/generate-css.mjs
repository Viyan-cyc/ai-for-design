// bridge 核对：EP 桥里引用的每个 var 名必须存在于 primitive/semantic 产物中
function checkBridge(bridgeVars, defined) {
  const missing = bridgeVars.filter((n) => !defined.has(`--${n}`));
  return missing;
}

function collectBridgeVars(bridgeText) {
  const out = new Set();
  for (const m of bridgeText.matchAll(/var\(--([a-z0-9-]+)\)/g)) out.add(m[1]);
  return [...out];
}

// ---------- index.css ----------
const INDEX_FILES = ['primitive.css', 'semantic.css', 'charts.css', 'code.css', 'frost.css', 'element-plus.css'];

function genIndex(sourceVersion) {
  const L = [];
  L.push(HEADER(sourceVersion));
  L.push(`/* 加载顺序：primitive（字面值）→ semantic（语义链）→ charts/code/frost（专项）→ element-plus（桥）。 */`);
  for (const f of INDEX_FILES) L.push(`@import "./${f}";`);
  return L.join('\n') + '\n';
}

// ---------- main ----------
const args = parseArgs(process.argv);
if (!args.tokens || !args.out) {
  console.error('Usage: node generate-css.mjs --tokens <tokens.json> --out <dir> [--check-only]');
  process.exit(1);
}

const data = JSON.parse(readFileSync(args.tokens, 'utf8'));
const tokens = data.tokens;
const sourceVersion = data.meta?.sourceVersion || data.meta?.['source-version'] || 'unversioned';

const pieces = {
  'primitive.css': genPrimitive(tokens, sourceVersion),
  'semantic.css': genSemantic(tokens, sourceVersion),
  'charts.css': genCharts(tokens, sourceVersion),
  'code.css': genCode(tokens, sourceVersion),
  'frost.css': genFrost(tokens, sourceVersion),
  'element-plus.css': EP_BRIDGE + '\n',
  'index.css': genIndex(sourceVersion),
};

// 核对：EP 桥 + 规则层引用的 var 全部有定义（禁造未定义值的 CSS 版）
const defined = new Set();
for (const [file, text] of Object.entries(pieces)) {
  if (file === 'element-plus.css' || file === 'index.css') continue;
  for (const m of text.matchAll(/^\s*--([A-Za-z0-9-]+)\s*:/gm)) defined.add(`--${m[1]}`);
}
const bridgeVars = collectBridgeVars(pieces['element-plus.css']);
const missing = checkBridge(bridgeVars, defined);
if (missing.length) {
  console.error(`BRIDGE-ERROR: EP 桥引用了未定义变量: ${missing.join(', ')}`);
  process.exit(2);
}
// 规则层死链扫描：所有 var() 引用必须可解析（var 名限 kebab-case 小写，含大写即为旧名残留）
const ruleTexts = Object.entries(pieces).filter(([f]) => f !== 'index.css');
const deadLinks = [];
for (const [file, text] of ruleTexts) {
  for (const m of text.matchAll(/var\(--([A-Za-z0-9-]+)\)/g)) {
    if (!defined.has(`--${m[1]}`)) deadLinks.push(`${file}: var(--${m[1]})`);
  }
}
if (deadLinks.length) {
  console.error(`DEAD-LINK: 生成产物存在未定义引用:\n  ${[...new Set(deadLinks)].join('\n  ')}`);
  process.exit(3);
}

if (args['check-only']) {
  console.log('check-only: bridge vars all defined ✓');
  process.exit(0);
}

mkdirSync(args.out, { recursive: true });
for (const [file, text] of Object.entries(pieces)) {
  writeFileSync(path.join(args.out, file), text, 'utf8');
}

