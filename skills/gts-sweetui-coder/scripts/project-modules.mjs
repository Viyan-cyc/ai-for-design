import fs from 'node:fs';
import path from 'node:path';

export function projectModules(root,sfc,{ignorePlugins=false}={}){
  const src=path.resolve(root,'src'),visited=new Set(),modules=new Set(),errors=[];
  function visit(file){
    file=path.resolve(file);
    if(ignorePlugins&&file===path.join(src,'native-plugins.js'))return;
    if(visited.has(file))return;visited.add(file);
    if(!file.startsWith(src+path.sep)||!fs.existsSync(file)){errors.push('Missing/escaping source dependency: '+file);return;}
    if(!/\.(vue|m?js)$/.test(file))return;
    let source=fs.readFileSync(file,'utf8');
    if(file.endsWith('.vue')){const {descriptor}=sfc.parse(source,{filename:file});source=[descriptor.script?.content,descriptor.scriptSetup?.content].filter(Boolean).join('\n');}
    let ast;try{ast=sfc.babelParse(source,{sourceType:'module'});}catch(e){errors.push(file+': '+e.message);return;}
    function add(spec){
      if(!spec.startsWith('.')){if(!/\.css$/.test(spec))modules.add(spec);return;}
      const base=path.resolve(path.dirname(file),spec);
      const candidate=[base,base+'.vue',base+'.js',base+'.mjs',path.join(base,'index.vue'),path.join(base,'index.js')].find(f=>fs.existsSync(f)&&fs.statSync(f).isFile());
      if(!candidate)errors.push(file+': unresolved '+spec);else visit(candidate);
    }
    function walk(n){if(!n||typeof n!=='object')return;
      if(['ImportDeclaration','ExportNamedDeclaration','ExportAllDeclaration'].includes(n.type)&&n.source)add(n.source.value);
      if(n.type==='CallExpression'&&n.callee?.type==='Import'){const value=n.arguments[0]?.value;if(typeof value==='string')add(value);else errors.push(file+': dynamic import must use a literal mapped module');}
      for(const x of Object.values(n))if(Array.isArray(x))x.forEach(walk);else if(x&&typeof x==='object')walk(x);
    }walk(ast);
  }
  for(const entry of ['App.vue','native-adapter.js','main.js'])visit(path.join(src,entry));
  return {modules:[...modules].sort(),files:[...visited],errors};
}
export function writeNativePlugins(root,needsDt){
  const code=needsDt?`// Generated by build from current reachable page imports. Original dt-ui dependency retained.\nimport * as DtUI from '@hw-dtn/dt-ui'\nexport function installExtras(app){app.use(DtUI)}\nexport function applyExtraTheme(theme,app){if(typeof DtUI.setTheme!=='function')throw new Error('Actual dt-ui setTheme missing');DtUI.setTheme(theme,app)}\n`:
    `// Generated by build: current page does not use dt-ui.\nexport function installExtras(){}\nexport function applyExtraTheme(){}\n`;
  const file=path.join(root,'src','native-plugins.js');if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==code)fs.writeFileSync(file,code);
  const styleFile=path.join(root,'src','native-styles.js'),styleCode=needsDt?"// Generated: standard bundlers load the same dt-ui CSS as offline preview.\nimport '@hw-dtn/dt-ui/dist/index.css'\n":"// Generated: no dt-ui styles needed by this page.\nexport {}\n";
  if(!fs.existsSync(styleFile)||fs.readFileSync(styleFile,'utf8')!==styleCode)fs.writeFileSync(styleFile,styleCode);
}
